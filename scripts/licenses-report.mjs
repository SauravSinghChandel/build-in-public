#!/usr/bin/env node
// Writes docs/licenses.md: direct dependencies of every workspace package with their
// licences (from `pnpm licenses list --json`), non-MIT call-outs, and the GSAP/Remotion check.
// Usage: pnpm licenses:report [output-file]
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.resolve(process.argv[2] || path.join(root, "docs/licenses.md"));
function pnpm(args) {
  // Under `pnpm run`, npm_execpath points at the running pnpm; otherwise use the pinned one.
  const execpath = process.env.npm_execpath;
  const [cmd, pre] =
    execpath && /pnpm/.test(execpath)
      ? execpath.endsWith(".js") || execpath.endsWith(".cjs")
        ? [process.execPath, [execpath]]
        : [execpath, []]
      : ["npx", ["--yes", "pnpm@10.34.9"]];
  return execFileSync(cmd, [...pre, ...args], {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
    stdio: ["ignore", "pipe", "inherit"],
  });
}
const byLicense = JSON.parse(pnpm(["licenses", "list", "--json", "-r"]));
const info = new Map();
for (const [license, pkgs] of Object.entries(byLicense))
  for (const p of pkgs) info.set(p.name, { license, versions: p.versions, homepage: p.homepage });
const workspaces = ["package.json", "apps/server/package.json", "apps/web/package.json", "packages/shared/package.json"];
const direct = new Map();
for (const file of workspaces) {
  const pkg = JSON.parse(fs.readFileSync(path.join(root, file), "utf8"));
  for (const [field, kind] of [["dependencies", "runtime"], ["devDependencies", "dev"]])
    for (const [name, spec] of Object.entries(pkg[field] || {})) {
      if (String(spec).startsWith("workspace:")) continue;
      const row = direct.get(name) || { name, kinds: new Set(), where: new Set() };
      row.kinds.add(kind);
      row.where.add(pkg.name || "root");
      direct.set(name, row);
    }
}
const rows = [...direct.values()].sort((a, b) => a.name.localeCompare(b.name));
const cell = (s) => String(s).replace(/\|/g, "\\|");
const lines = [
  "# Licences",
  "",
  "Generated by `pnpm licenses:report` from `pnpm licenses list --json`. Do not edit by hand.",
  "",
  "Build in Public is MIT-licensed. Direct dependencies:",
  "",
  "| Package | Version | Licence | Used in | Type |",
  "|---|---|---|---|---|",
  ...rows.map((r) => {
    const i = info.get(r.name);
    return `| ${cell(r.name)} | ${i ? i.versions.join(", ") : "?"} | ${cell(i?.license || "unknown")} | ${[...r.where].join(", ")} | ${[...r.kinds].join(", ")} |`;
  }),
  "",
  "## Not MIT",
  "",
  ...rows
    .filter((r) => info.get(r.name)?.license && info.get(r.name).license !== "MIT")
    .map((r) => `- ${r.name}: ${info.get(r.name).license}${[...r.kinds].includes("runtime") ? "" : " (development only, not shipped)"}`),
  "- FFmpeg: LGPL/GPL, used as a system binary. It is not bundled or distributed.",
  "- IBM Plex Sans and Mono fonts (via @fontsource): OFL-1.1.",
  "",
  "## All packages by licence (including transitive)",
  "",
  "| Licence | Packages |",
  "|---|---|",
  ...Object.entries(byLicense)
    .sort((a, b) => b[1].length - a[1].length)
    .map(([l, p]) => `| ${cell(l)} | ${p.length} |`),
  "",
  "## GSAP and Remotion",
  "",
];
const banned = [...info.keys()].filter((n) => /^(gsap|remotion|@remotion\/)/.test(n));
lines.push(
  banned.length
    ? `Found: ${banned.join(", ")}. Remove them before release.`
    : "Neither GSAP nor Remotion is present in the dependency tree. CI enforces this with `pnpm licences:guard`.",
  "",
);
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${out} (${rows.length} direct dependencies).`);
